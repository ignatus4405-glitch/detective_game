def load_case(case_id: str) -> Optional[Dict]:
    # сначала пробуем файл с именем = id (быстрый путь)
    file_path = CASES_DIR / f"{case_id}.json"
    if file_path.exists():
        try:
            with open(file_path, "r", encoding="utf-8") as f:
                return json.load(f)
        except Exception:
            pass
    # затем ищем дело по полю id среди всех файлов (например, example.json)
    if CASES_DIR.exists():
        for p in CASES_DIR.glob("*.json"):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    case = json.load(f)
            except Exception:
                continue
            if isinstance(case, dict) and case.get("id") == case_id:
                return case
    # затем встроенные
    for c in BUILTIN_CASES:
        if c["id"] == case_id:
            return c
    return None

def list_cases() -> List[Dict]:
    cases = []
    # из файлов
    if CASES_DIR.exists():
        for p in CASES_DIR.glob("*.json"):
            try:
                with open(p, "r", encoding="utf-8") as f:
                    cases.append(json.load(f))
            except Exception:
                continue
    # встроенные — добавляем если нет дубликатов
    existing_ids = {c["id"] for c in cases}
    for c in BUILTIN_CASES:
        if c["id"] not in existing_ids:
            cases.append(c)
    return cases

def get_location(case: Dict, loc_id: str) -> Optional[Dict]:
    for loc in case.get("locations", []):
        if loc["id"] == loc_id:
            return loc
    return None

def _merge_interactive_topics(cases: List[Dict]) -> None:
    """Добавить темы с выбором реплик и бонусы за доверие.

    Темы идут первыми, старые линейные вопросы остаются следом — игрок
    видит и новые выборы, и прежние сюжетные реплики.
    """
    for case in cases:
        for char in case.get("characters", []):
            extra = INTERACTIVE_TOPICS.get((case["id"], char.get("id")))
            if extra:
                legacy = [t for t in char.get("dialogue", []) if t.get("q")]
                char["dialogue"] = [dict(topic) for topic in extra] + legacy
            bonus = TRUST_BONUSES.get((case["id"], char.get("id")))
            if bonus:
                char["trust_bonus"] = dict(bonus)


def _merge_ending_variants(cases: List[Dict]) -> None:
    """Добавить варианты концовок (несколько финалов на дело)."""
    for case in cases:
        endings = case.setdefault("endings", {})
        for suspect in case.get("suspects", []):
            variants = ENDING_VARIANTS.get((case["id"], suspect.get("id")))
            if not variants:
                continue
            ending = endings.setdefault(
                suspect.get("id"),
                {
                    "success": bool(suspect.get("is_culprit")),
                    "title": suspect.get("name", "Финал"),
                    "text": "История окончена.",
                    "rank": "B" if suspect.get("is_culprit") else "F",
                },
            )
            ending.setdefault("variants", [dict(v) for v in variants])


_merge_interactive_topics(BUILTIN_CASES)
_merge_ending_variants(BUILTIN_CASES)


def get_clue(case: Dict, clue_id: str) -> Optional[Dict]:
    for cl in case.get("clues", []):
        if cl["id"] == clue_id:
            return cl
    return None

def get_character(case: Dict, char_id: str) -> Optional[Dict]:
    for ch in case.get("characters", []):
        if ch["id"] == char_id:
            return ch
    return None
